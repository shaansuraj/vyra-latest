#!/usr/bin/env bash
set -euo pipefail

RELAY_BASE="${RELAY_BASE:-http://127.0.0.1:8020}"
TOKEN="${RELAY_TOKEN:-}"
LOAD_SECONDS="${SMOKE_LOAD_SECONDS:-45}"
IDENTITY_TRACKS="${SMOKE_IDENTITY_TRACKS:-8}"
MEDIA_IDS_CSV="${SMOKE_MEDIA_IDS:-}"
QUERY_TEXT="${SMOKE_QUERY_TEXT:-What happened today?}"
TMP_QUERY="${TMPDIR:-/tmp}/vyra_smoke_query.json"

echo "[smoke] relay base: ${RELAY_BASE}"

if ! command -v jq >/dev/null 2>&1; then
  echo "[smoke] jq is required"
  exit 1
fi

curl_json() {
  local method="$1"; shift
  local url="$1"; shift
  if [[ -n "${TOKEN}" ]]; then
    curl -sS -X "${method}" "${url}" -H "Authorization: Bearer ${TOKEN}" "$@"
  else
    curl -sS -X "${method}" "${url}" "$@"
  fi
}

wait_http_ok() {
  local url="$1"
  local attempts="${2:-30}"
  local sleep_s="${3:-1}"
  local i=0
  until curl -fsS "${url}" >/dev/null; do
    i=$((i + 1))
    if [[ "${i}" -ge "${attempts}" ]]; then
      echo "[smoke] endpoint did not become ready: ${url}"
      return 1
    fi
    sleep "${sleep_s}"
  done
}

fetch_media_ids() {
  local ids=()
  if [[ -n "${MEDIA_IDS_CSV}" ]]; then
    IFS=',' read -r -a ids <<<"${MEDIA_IDS_CSV}"
  elif [[ -n "${TOKEN}" ]]; then
    mapfile -t ids < <(curl_json GET "${RELAY_BASE}/cameras" | jq -r '.[].id' | head -n 6)
  fi
  if [[ "${#ids[@]}" -eq 0 ]]; then
    ids=("camera-a" "camera-b" "camera-c")
  fi
  printf "%s\n" "${ids[@]}"
}

run_identity_simulation() {
  local media_ids=("$@")
  echo "[smoke] identity simulation across ${#media_ids[@]} media ids x ${IDENTITY_TRACKS} tracks"

  for media_id in "${media_ids[@]}"; do
    for track_id in $(seq 1 "${IDENTITY_TRACKS}"); do
      local emb
      case $((track_id % 3)) in
        0) emb='[0.98,0.02,0.00]' ;;
        1) emb='[0.03,0.95,0.02]' ;;
        *) emb='[0.01,0.05,0.94]' ;;
      esac
      local payload
      payload="$(jq -cn \
        --arg media "${media_id}" \
        --argjson track "${track_id}" \
        --argjson emb "${emb}" \
        '{media_id:$media, track_id:$track, embedding:$emb, camera_name:$media, camera_timestamp:(now|todateiso8601)}')"
      curl_json POST "${RELAY_BASE}/cv/person-identity/resolve" \
        -H "Content-Type: application/json" \
        -d "${payload}" | jq -e '.global_person_id != null' >/dev/null
    done
  done

  for media_id in "${media_ids[@]}"; do
    curl_json GET "${RELAY_BASE}/cv/person-identities?media_id=${media_id}" \
      | jq -e 'type=="object" and (keys | length) >= 1' >/dev/null
  done
}

run_parallel_load_iteration() {
  local media_ids=("$@")
  local media_idx=$((RANDOM % ${#media_ids[@]}))
  local media_id="${media_ids[$media_idx]}"
  local pids=()

  if [[ -n "${TOKEN}" ]]; then
    curl_json GET "${RELAY_BASE}/system/workers" >/dev/null & pids+=("$!")
    curl_json GET "${RELAY_BASE}/events?limit=100&offset=0" >/dev/null & pids+=("$!")
    curl_json GET "${RELAY_BASE}/events/count" >/dev/null & pids+=("$!")
    curl_json GET "${RELAY_BASE}/search?query=person&limit=20&offset=0" >/dev/null & pids+=("$!")
    curl_json GET "${RELAY_BASE}/daily-summary?date=today" >/dev/null & pids+=("$!")
    curl_json GET "${RELAY_BASE}/system/custom/workers" >/dev/null & pids+=("$!")
  fi

  curl_json GET "${RELAY_BASE}/cv/person-identities?media_id=${media_id}" >/dev/null & pids+=("$!")

  local pid
  for pid in "${pids[@]}"; do
    wait "${pid}"
  done
}

run_timeline_smoke() {
  echo "[smoke] checking timeline endpoints"

  local identities_json
  identities_json="$(curl_json GET "${RELAY_BASE}/timeline/identities?limit=20")"
  echo "${identities_json}" | jq -e 'type=="array"' >/dev/null

  local moments_json
  moments_json="$(curl_json GET "${RELAY_BASE}/timeline/moments?limit=20")"
  echo "${moments_json}" | jq -e 'type=="array"' >/dev/null

  local identity_id
  identity_id="$(echo "${identities_json}" | jq -r '.[0].global_person_id // empty')"
  if [[ -z "${identity_id}" ]]; then
    echo "[smoke] no timeline identities found; timeline empty-state endpoints passed."
    return 0
  fi

  curl_json GET "${RELAY_BASE}/timeline/journey?global_person_id=$(printf '%s' "${identity_id}" | jq -sRr @uri)&limit=50" \
    | jq -e '.identity.global_person_id != null and (.moments | type=="array")' >/dev/null

  curl_json GET "${RELAY_BASE}/timeline/appearance-search?global_person_id=$(printf '%s' "${identity_id}" | jq -sRr @uri)&limit=5" \
    | jq -e 'type=="array"' >/dev/null

  local moment_id
  moment_id="$(echo "${moments_json}" | jq -r '.[0].id // empty')"
  if [[ -z "${moment_id}" ]]; then
    echo "[smoke] timeline identities exist but no moments returned; journey smoke passed."
    return 0
  fi

  local case_json case_id
  case_json="$(curl_json POST "${RELAY_BASE}/timeline/cases" \
    -H "Content-Type: application/json" \
    -d '{"title":"Smoke Timeline Case","owner":"smoke","notes":"generated by e2e_smoke.sh"}')"
  case_id="$(echo "${case_json}" | jq -r '.id // empty')"
  if [[ -z "${case_id}" ]]; then
    echo "[smoke] failed to create timeline case"
    echo "${case_json}"
    exit 1
  fi

  curl_json POST "${RELAY_BASE}/timeline/cases/${case_id}/items" \
    -H "Content-Type: application/json" \
    -d "$(jq -cn --arg moment "${moment_id}" '{moment_ids:[$moment], note:"smoke pin"}')" \
    | jq -e 'type=="array"' >/dev/null

  curl_json POST "${RELAY_BASE}/timeline/evidence-locks" \
    -H "Content-Type: application/json" \
    -d "$(jq -cn --arg case_id "${case_id}" --arg moment "${moment_id}" '{title:"Smoke evidence lock", case_id:$case_id, moment_ids:[$moment]}')" \
    | jq -e '.id != null' >/dev/null

  curl_json POST "${RELAY_BASE}/timeline/cases/${case_id}/export" \
    | jq -e '.case.id != null and (.moments | type=="array") and (.csv_rows | type=="array") and (.snapshot_hashes | type=="array")' >/dev/null
}

echo "[smoke] checking unauth health endpoints"
wait_http_ok "${RELAY_BASE}/flags" 90 1
wait_http_ok "${RELAY_BASE}/health" 10 1 || true

mapfile -t MEDIA_IDS < <(fetch_media_ids)
run_identity_simulation "${MEDIA_IDS[@]}"

if [[ -z "${TOKEN}" ]]; then
  echo "[smoke] RELAY_TOKEN not set; identity + health smoke completed."
  exit 0
fi

echo "[smoke] checking authenticated endpoints"
curl_json GET "${RELAY_BASE}/agents" | jq -e 'type=="array"' >/dev/null
curl_json GET "${RELAY_BASE}/system/workers" | jq -e '.workers != null' >/dev/null
run_timeline_smoke

echo "[smoke] start Ask-AI worker"
curl_json POST "${RELAY_BASE}/system/llm/start" \
  -H "Content-Type: application/json" \
  -d '{"model_id":"google/gemma-3-1b-it"}' | jq -e '.started == true' >/dev/null

echo "[smoke] wait for llm status endpoint"
for _ in $(seq 1 45); do
  if curl_json GET "${RELAY_BASE}/system/llm/status" | jq -e '.running == true' >/dev/null; then
    break
  fi
  sleep 1
done
curl_json GET "${RELAY_BASE}/system/llm/status" | jq -e '.running == true' >/dev/null

echo "[smoke] run query (expects 200 or actionable 409)"
query_status="$(curl -sS -o "${TMP_QUERY}" -w '%{http_code}' \
  -X POST "${RELAY_BASE}/query" \
  -H "Authorization: Bearer ${TOKEN}" \
  -H "Content-Type: application/json" \
  -d "{\"question\":\"${QUERY_TEXT}\",\"date\":\"today\"}")"
if [[ "${query_status}" != "200" && "${query_status}" != "409" ]]; then
  echo "[smoke] /query returned unexpected status: ${query_status}"
  cat "${TMP_QUERY}"
  exit 1
fi
if [[ "${query_status}" == "409" ]]; then
  jq -e '.code=="llm_worker_not_running"' "${TMP_QUERY}" >/dev/null
fi

echo "[smoke] scale worker pools up/down"
for pool in ppe objdet vlm face; do
  curl_json POST "${RELAY_BASE}/system/scale" \
    -H "Content-Type: application/json" \
    -d "{\"type\":\"${pool}\",\"replicas\":1}" \
    | jq -e --arg pool "${pool}" '.type == $pool and .replicas == 1' >/dev/null
done
sleep 2
for pool in ppe objdet vlm face; do
  curl_json GET "${RELAY_BASE}/system/workers" \
    | jq -e --arg pool "${pool}" '.workers[$pool].desired >= 1' >/dev/null
done
for pool in ppe objdet vlm face; do
  curl_json POST "${RELAY_BASE}/system/scale" \
    -H "Content-Type: application/json" \
    -d "{\"type\":\"${pool}\",\"replicas\":0}" \
    | jq -e --arg pool "${pool}" '.type == $pool and .replicas == 0' >/dev/null
done

echo "[smoke] multi-camera load loop for ${LOAD_SECONDS}s"
end_ts=$(( $(date +%s) + LOAD_SECONDS ))
while [[ "$(date +%s)" -lt "${end_ts}" ]]; do
  run_parallel_load_iteration "${MEDIA_IDS[@]}"
done

echo "[smoke] completed successfully"
